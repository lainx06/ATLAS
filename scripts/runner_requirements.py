"""Regenerate docker/runner-requirements.txt: the runner image's pinned, hashed dependency set.

Inputs: docker/runner-requirements.in (direct runtime imports of the mounted code, plus the
Parquet engine) constrained to the versions in uv.lock, resolved for the image platform
(CPython 3.11, x86_64 manylinux, wheels only). Needs network access to the package index.

Run: uv run --locked python scripts/runner_requirements.py
"""

import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
IN_FILE = ROOT / "docker" / "runner-requirements.in"
OUT_FILE = ROOT / "docker" / "runner-requirements.txt"
HEADER = (
    "# Generated by scripts/runner_requirements.py from docker/runner-requirements.in,\n"
    "# constrained to uv.lock, for CPython 3.11 on x86_64 manylinux (wheels only).\n"
    "# Installed in Dockerfile.runner with --require-hashes --no-deps. Do not edit.\n"
)


def main() -> int:
    with tempfile.TemporaryDirectory() as tmp:
        constraints = Path(tmp) / "uv-lock-constraints.txt"
        compiled = Path(tmp) / "compiled.txt"
        export = ["uv", "export", "--frozen", "--no-dev", "--no-hashes"]
        export += ["--no-emit-project", "--no-header", "--format", "requirements-txt"]
        constraints.write_text(
            subprocess.run(
                export, cwd=ROOT, check=True, capture_output=True, text=True
            ).stdout,
            encoding="utf-8",
        )
        compile_cmd = ["uv", "pip", "compile", str(IN_FILE), "-c", str(constraints)]
        compile_cmd += ["--python-version", "3.11"]
        compile_cmd += ["--python-platform", "x86_64-manylinux_2_28"]
        compile_cmd += [
            "--only-binary",
            ":all:",
            "--generate-hashes",
            "--no-header",
            "--quiet",
        ]
        compile_cmd += ["-o", str(compiled)]
        subprocess.run(compile_cmd, cwd=ROOT, check=True)
        body = compiled.read_text(encoding="utf-8")
        # The temporary constraint path is not meaningful; name its source instead.
        body = body.replace(constraints.as_posix(), "uv.lock").replace(
            str(constraints), "uv.lock"
        )
        body = body.replace(IN_FILE.as_posix(), "docker/runner-requirements.in")
        body = body.replace(str(IN_FILE), "docker/runner-requirements.in")
    OUT_FILE.write_text(HEADER + body, encoding="utf-8", newline="\n")
    print(f"wrote {OUT_FILE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
